# 大仓库的 add / commit 可能显著超过默认 30s（首次提交全量入库）
_HEAVY_GIT_TIMEOUT = 120

# LaTeX 编译产物 .gitignore 模板（项目已有 .gitignore 时尊重现状，不覆盖）
