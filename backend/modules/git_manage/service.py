def _fail(status_code: int, code: str, message: str) -> HTTPException:
    return HTTPException(
        status_code=status_code, detail={"error": code, "message": message}
    )


async def _workspace_root(workspace_id: str) -> Path:
    """解析当前打开项目的根目录（未打开项目抛 RuntimeError → 400）。"""
    project = get_project_manager_for_workspace(workspace_id)
    if not project.is_open:
        raise RuntimeError("No project opened")
    return Path(project.root_path).resolve()


def _has_own_git_dir(root: Path) -> bool:
    """项目根是否自带版本库（``.git`` 目录或文件——worktree/submodule）。

    以"自带 .git"为准而非 git 的仓库发现语义：项目落在某个父级仓库内
    （如部署目录本身是 git 仓库）不视为已初始化；init 在项目根创建独立
    仓库后，nearest-.git 语义保证后续 git 操作以项目仓库为准。"""
    return (root / ".git").exists()


# ── status ────────────────────────────────────────────────────────
async def get_status(workspace_id: str = "") -> GitStatusResult:
    """版本状态总览：未初始化时 initialized=false 且其余字段为空值。"""
    root = await _workspace_root(workspace_id)
    max_bytes = git_dir_cap_bytes()

    if not _has_own_git_dir(root):
        return GitStatusResult(initialized=False, git_dir_max_bytes=max_bytes)

    context = await get_project_context(workspace_id)
    branch = await git_diff_process.run_git(
        context.git_root, ["branch", "--show-current"]
    )
    changes = await _list_changes(context)
    git_bytes = await asyncio.to_thread(git_dir_size, context.git_root)
    return GitStatusResult(
        initialized=True,
        current_branch=branch.stdout.strip() if branch.returncode == 0 else "",
        is_dirty=bool(changes),
        changes=changes,
        git_dir_size_bytes=git_bytes,
        git_dir_max_bytes=max_bytes,
        last_commit=await _last_commit(context.git_root),
    )


async def _list_changes(context: ProjectContext) -> list[GitChangeItem]:
    """工作区变更列表（porcelain v1 -z -uall，路径转为项目内相对路径）。

    仓库根相对路径经 project_prefix 过滤转换：项目前缀之外（父仓库其他
    目录）的变更不展示、不计脏标记。应用内部元数据目录 ``.latexcellence/``
    （手动主文件标记等）同样不展示——与文件树/扫描的隐藏目录口径一致，
    兜底 .gitignore 排除缺失（项目自带 .gitignore 时 init 模板不写入）
    或标记文件已被跟踪的仓库。"""
    result = await git_diff_process.run_git(
        context.git_root,
        ["status", "--porcelain=v1", "-z", "-uall"],
    )
    if result.returncode != 0:
        raise RuntimeError(
            git_diff_process.redact_command_output_for_user(
                result.stderr.strip() or "Git status failed", context.git_root
            )
        )

    prefix = context.project_prefix.as_posix()
    changes: list[GitChangeItem] = []
    skip_next = False
    for entry in result.stdout.split("\x00"):
        if not entry:
            continue
        if skip_next:  # 上一条是 rename/copy：本字段是其原始路径，跳过
            skip_next = False
            continue
        xy, path = entry[:2], entry[3:]
        if not path:
            continue
        if xy[0] in ("R", "C"):
            skip_next = True
        repo_path = PurePosixPath(path)
        if prefix:
            try:
                rel = repo_path.relative_to(prefix)
            except ValueError:
                continue
        else:
            rel = repo_path
        if rel.parts[0] == ".latexcellence":
            continue
        changes.append(GitChangeItem(path=rel.as_posix(), kind=_change_kind(xy)))
    return changes


def _change_kind(xy: str) -> str:
    """porcelain XY 状态码 → 前端三种徽标（新增/修改/删除）。"""
    if "D" in xy:
        return "deleted"
    if "?" in xy or "A" in xy:
        return "added"
    return "modified"


async def _last_commit(git_root: Path) -> GitLastCommit | None:
    result = await git_diff_process.run_git(
        git_root,
        ["log", "-1", "--pretty=format:%h%x00%s%x00%an%x00%aI"],
    )
    if result.returncode != 0:
        # 全新仓库还没有任何提交（如用户手动 git init 后未 commit）
        return None
    parts = result.stdout.strip().split("\x00")
    if len(parts) < 4:
        return None
    return GitLastCommit(
        short_hash=parts[0], subject=parts[1], author=parts[2], date=parts[3]
    )


# ── init ──────────────────────────────────────────────────────────
async def init_repository(workspace_id: str = "") -> GitCommitResult:
    """为当前打开的项目初始化版本库（已初始化 → 409；预估超上限 → 413）。"""
    root = await _workspace_root(workspace_id)
    return await _init_repository_at(root)


async def _init_repository_at(root: Path) -> GitCommitResult:
    if _has_own_git_dir(root):
        raise _fail(
            409,
            "git_already_initialized",
            "Version control is already initialized for this project",
        )

    await git_diff_process.run_git_checked(root, ["init"], timeout=_HEAVY_GIT_TIMEOUT)
    wrote_gitignore = await asyncio.to_thread(_write_gitignore, root)
    # 计数与体积预估须在 add 之前：add -A 后工作区即干净，porcelain 不再有条目
    staged_count, pending_bytes = await _scan_pending(root)
    # 上限预检（未压缩口径，与 commit 预估一致）：超限则整体回滚本次 init。
    # 否则超限 .git 落地后，commit 侧预检恒为超限，用户将永久无法提交。
    if pending_bytes > git_dir_cap_bytes():
        await asyncio.to_thread(_rollback_init, root, wrote_gitignore)
        raise _fail(
            413,
            "git_history_too_large",
            "Git history (.git) would exceed the size limit; initialization rejected",
        )
    identity = await _identity_args()
    await git_diff_process.run_git_checked(
        root, ["add", "-A"], timeout=_HEAVY_GIT_TIMEOUT
    )
    await git_diff_process.run_git_checked(
        root,
        [*identity, "commit", "-m", "Initial commit"],
        timeout=_HEAVY_GIT_TIMEOUT,
    )
    info = await git_diff_process.run_git_checked(
        root, ["log", "-1", "--pretty=format:%h%x00%s"]
    )
    parts = info.stdout.strip().split("\x00")
    git_bytes = await asyncio.to_thread(git_dir_size, root)
    return GitCommitResult(
        short_hash=parts[0] if parts else "",
        subject=parts[1] if len(parts) > 1 else "Initial commit",
        committed_count=staged_count,
        git_dir_size_bytes=git_bytes,
    )


def _write_gitignore(root: Path) -> bool:
    """项目根无 .gitignore 时原子写入模板；返回是否写入。"""
    target = root / ".gitignore"
    if target.exists():
        return False
    tmp = target.with_name(".gitignore.latexcellence.tmp")
    tmp.write_text(GITIGNORE_TEMPLATE, encoding="utf-8")
    tmp.replace(target)
    return True


def _rollback_init(root: Path, wrote_gitignore: bool) -> None:
    """上限拒绝路径整体回滚：删除刚创建的 .git 与（若由本模块写入的）
    .gitignore，使项目回到未初始化状态，用户可在调大上限后重试。"""
    shutil.rmtree(root / ".git", ignore_errors=True)
    if wrote_gitignore:
        (root / ".gitignore").unlink(missing_ok=True)
    if (root / ".git").exists():
        # 沙箱容器 uid 与宿主不一致等场景可能清理不净：留下空仓库不影响
        # 配额口径（.git 豁免），但要留服务端日志便于排查
        logger.warning(
            "Git init rollback incomplete for %s: .git could not be fully removed",
            root,
        )


async def _scan_pending(root: Path) -> tuple[int, int]:
    """porcelain 扫描：返回（将入库文件数, 未压缩总体积）。

    init 场景在工作区尚未 add 时调用，条目即初始提交的文件清单；体积与
    commit 预估同一口径。失败容错为 (0, 0)。"""
    result = await git_diff_process.run_git(
        root, ["status", "--porcelain=v1", "-z", "-uall"]
    )
    if result.returncode != 0:
        return 0, 0

    def _tally() -> tuple[int, int]:
        count, total = 0, 0
        for entry in result.stdout.split("\x00"):
            if not entry:
                continue
            count += 1
            path = root / entry[3:]
            try:
                if path.is_file():
                    total += path.stat().st_size
            except OSError:
                continue
        return count, total

    return await asyncio.to_thread(_tally)


async def _identity_args() -> list[str]:
    """commit 身份（每次经 -c 注入，不落全局 git 配置）。

    多用户模式取操作者平台用户名 + 确定性 email；单用户取固定身份。
    用户名查询走 to_thread（SQLite 同步驱动，不阻塞事件循环）。"""
    if get_config().multi_user.enabled:
        user_id = userspace.get_current_user_id() or ""
        if user_id:
            row = await asyncio.to_thread(
                db_query_one,
                "SELECT username FROM users WHERE id = ?",
                (user_id,),
            )
            name = (row["username"] if row else "") or "LaTeXcellence"
            return [
                "-c",
                f"user.name={name}",
                "-c",
                f"user.email={user_id}@users.latexcellence.local",
            ]
    return ["-c", "user.name=LaTeXcellence", "-c", "user.email=latexcellence@local"]


# ── commit ────────────────────────────────────────────────────────
async def commit_all(workspace_id: str = "", message: str = "") -> GitCommitResult:
    """add -A + commit（无变更 → 400；预估超 .git 上限 → 413）。"""
    context = await get_project_context(workspace_id)
    changes = await _list_changes(context)
    if not changes:
        raise _fail(400, "git_no_changes", "Nothing to commit")

    # 上限预估：当前 .git 体积 + Σ(新增/修改文件 stat 大小)。git 对象
    # 压缩后通常更小，取未压缩口径偏保守；删除不计。
    pending_bytes = 0
    for change in changes:
        if change.kind == "deleted":
            continue
        try:
            file_path = resolve_project_path(context.root, change.path)
        except ValueError:
            continue  # 越界/符号链接等异常路径不参与预估（add 阶段 git 自行处理）
        try:
            if file_path.is_file():
                pending_bytes += file_path.stat().st_size
        except OSError:
            continue
    git_bytes = await asyncio.to_thread(git_dir_size, context.git_root)
    if git_bytes + pending_bytes > git_dir_cap_bytes():
        raise _fail(
            413,
            "git_history_too_large",
            "Git history (.git) would exceed the size limit; commit rejected",
        )

    identity = await _identity_args()
    try:
        await git_diff_process.run_git_checked(
            context.git_root, ["add", "-A"], timeout=_HEAVY_GIT_TIMEOUT
        )
        await git_diff_process.run_git_checked(
            context.git_root,
            [*identity, "commit", "-m", message],
            timeout=_HEAVY_GIT_TIMEOUT,
        )
    except RuntimeError as e:
        if "index.lock" in str(e):
            raise _fail(
                409,
                "git_repository_locked",
                "Git repository is locked by another operation, please retry later",
            ) from e
        raise

    info = await git_diff_process.run_git_checked(
        context.git_root, ["log", "-1", "--pretty=format:%h%x00%s"]
    )
    parts = info.stdout.strip().split("\x00")
    git_bytes = await asyncio.to_thread(git_dir_size, context.git_root)
    return GitCommitResult(
        short_hash=parts[0] if parts else "",
        subject=parts[1] if len(parts) > 1 else message,
        committed_count=len(changes),
        git_dir_size_bytes=git_bytes,
    )


# ── log ───────────────────────────────────────────────────────────
async def get_log(
    workspace_id: str = "", limit: int = 50, offset: int = 0
) -> list[GitLogEntry]:
    """提交历史（limit/offset 分页；空仓库返回空列表）。"""
    context = await get_project_context(workspace_id)
    limit = max(1, min(int(limit), 200))
    offset = max(0, int(offset))
    result = await git_diff_process.run_git(
        context.git_root,
        [
            "log",
            f"--max-count={limit}",
            f"--skip={offset}",
            "--pretty=format:%H%x00%h%x00%s%x00%an%x00%aI",
        ],
    )
    if result.returncode != 0:
        stderr = result.stderr.strip()
        if "does not have any commits yet" in stderr:
            return []
        raise RuntimeError(
            git_diff_process.redact_command_output_for_user(
                stderr or result.stdout.strip() or "Git log failed", context.git_root
            )
        )
    entries: list[GitLogEntry] = []
    for line in result.stdout.splitlines():
        parts = line.split("\x00")
        if len(parts) < 5:
            continue
        entries.append(
            GitLogEntry(
                hash=parts[0],
                short_hash=parts[1],
                subject=parts[2],
                author_name=parts[3],
                date_iso=parts[4],
            )
        )
    return entries


